/** 按当前路由判定角色：/admin* → admin，/reviewer* → reviewer，其余 → member */
export function guideRoleFromPath(pathname: string): GuideRoleKey {
  if (pathname.startsWith('/admin')) return 'admin';
  if (pathname.startsWith('/reviewer')) return 'reviewer';
  return 'member';
}
