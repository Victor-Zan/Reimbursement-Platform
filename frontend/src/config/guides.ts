/**
 * 操作指南内容数据 —— 报销人 / 审核员 / 管理员 三份分页式新手导航。
 *
 * 图片约定：截图由人工提供，放入 frontend/public/guide/ 目录（命名 {role}-{页码}.png），
 * 组件按 image 字段引用；文件缺失时页面显示"截图待补充"占位，文字照常可读，
 * 补图后刷新即生效，无需改代码。
 *
 * 文字约定：p.text / list.items / tip.text 中可用 **成对标记** 将关键文字渲染为紫色强调。
 */

export type GuideRoleKey = 'member' | 'reviewer' | 'admin';

export type GuideBlock =
  | { type: 'p'; text: string }         // 正文段落
  | { type: 'list'; items: string[] }   // 要点列表（紫色圆点）
  | { type: 'tip'; text: string };      // 重要提示条（紫底 + 金色左条）

export interface GuidePage {
  title: string;          // 页标题
  icon?: string;          // Icon.tsx 注册表中的图标名，缺省 'info'
  image?: string | string[]; // 静态图片路径 '/guide/member-2.png'，或一页多张截图数组（按序竖排）；缺省则该页无图片区
  imageCaption?: string;  // 图片下方说明（兼作 img alt）
  blocks: GuideBlock[];   // 页面内容块
  blocksByImage?: GuideBlock[][]; // 多图页正文：按图片下标分组，滑动到第 i 张图时显示 blocksByImage[i]；缺省回退 blocks
}

export interface GuideBook {
  id: GuideRoleKey;
  title: string;          // 指南书名，如"报销人操作指南"
  pages: GuidePage[];
}

